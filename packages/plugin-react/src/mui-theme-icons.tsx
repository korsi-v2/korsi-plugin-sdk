/** The avatar group's «+n», in the primary colour's tint, sized to the avatars around it. */
export function renderSurplus(surplus: number) {
  return (
    <Box
      component="span"
      sx={(theme: Theme) => {
        const primary = theme.palette.primary as { lighter?: string; dark: string };
        return {
          width: 1,
          height: 1,
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'center',
          position: 'absolute',
          color: primary.dark,
          backgroundColor: primary.lighter ?? theme.palette.primary.light,
          fontSize: {
            '@': theme.typography.pxToRem(11),
            '@32': theme.typography.pxToRem(12),
            '@36': theme.typography.pxToRem(13),
            '@40': theme.typography.pxToRem(14),
            '@64': theme.typography.pxToRem(18),
          },
        };
      }}
    >
      +{surplus}
    </Box>
  );
}
